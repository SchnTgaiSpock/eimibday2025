/// Generate a board from random settings
export function generateBoard(gen: EimisweeperRandomBoardgen): EimisweeperGame {
  if (gen.info.geometry !== 'square') {
    alert('Error: only square games currently supported for random generation');
    return undefined;
  }
  if (gen.info.noGuessing === true) {
    alert('Error: no-guess random games not supported yet');
    return undefined;
  }
  if (gen.randomSeed === undefined) {
    // TODO: implement this? e.g. for Daily
    gen.randomSeed = Random();
  }
  // generate cell positions
  let cell_positions: Pos[] = [];
  for (let y=0; y < gen.info.y; y++) {
    for (let x=0; x < gen.info.x; x++) {
      // positions can be included/excluded based on geometry
      cell_positions.push({x: x, y: y,});
    }
  }
  const index = buildIndex(cell_positions);
  // calculate cell adjacency according to geometry and build real list
  const adj: number[][] = buildAdjacency(cell_positions, index, gen.geometry);
  let cells: Cell[] = [];
  for (const [idx, pos] of Object.entries(cell_positions)) {
    cells.push({
      pos: pos,
      adjacent: adj[idx],
      content: "", // mines have not been placed yet
      isBomb: false,
      isOpen: true,
      hidden: true,
      flagged: false,
    });
  }
  return {
    board: {
      cells: cells,
      index: index,
    },
    info: gen.info,
    minesPlaced: false,
    generator: gen,
  };
}


