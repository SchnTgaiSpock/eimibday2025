// Add defaults
function setPuzzleDefaults(puzzle: UncheckedPuzzle): EimisweeperPuzzleData {
  return {...puzzle,
    info: {
      geometry: 'square',
      totalMines: (puzzle.data.content.match(/\*/g)||[]).length,
      showTotalMines: true,
      totalQs: (puzzle.data.content.match(/[^0-9* \n]/g)||[]).length,
      showTotalQs: false,
      noGuessing: true,
      ...puzzle.info
    }
  }
}
export const puzzles: EimisweeperPuzzleData[] = (puzzlesJson as UncheckedPuzzle[]).map(setPuzzleDefaults);

